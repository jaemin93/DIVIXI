const dicts: Record<Lang, Record<Key, string>> = { ko, en };

/** Reactive language state; the store sets it from the preference. */
export const i18n = $state<{ lang: Lang }>({ lang: "ko" });

/** What "system" means on this machine. */
export function systemLang(): Lang {
  const tag = typeof navigator !== "undefined" ? navigator.language : "ko";
  return tag.toLowerCase().startsWith("ko") ? "ko" : "en";
}

/** Look a key up in the current language, filling `{var}` slots. */
export function t(key: Key, vars?: Record<string, string | number>): string {
  let s = dicts[i18n.lang][key] ?? ko[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}
